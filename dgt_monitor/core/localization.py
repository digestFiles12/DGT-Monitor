def normalize_locale(locale: str | None) -> str:
    language = (locale or DEFAULT_LOCALE).split("-", 1)[0].casefold()
    return language if language in SUPPORTED_LOCALES else DEFAULT_LOCALE


class Translator:
    def __init__(self, locale: str | None = DEFAULT_LOCALE, translations: dict[str, str] | None = None) -> None:
        self.locale = normalize_locale(locale)
        self._translations = translations or TRANSLATION_CATALOG[self.locale]

    def translate(self, value: str | None) -> str:
        if not value:
            return self.missing_label
        if str(value).strip().upper() in {"N/A", "NA"}:
            return self.missing_label
        return self._translations.get(value, humanize_code(value))

    def translate_compound(self, value: str | None, separator: str = " - ") -> str:
        if not value:
            return self.missing_label
        return separator.join(self.translate(part.strip()) for part in value.split(separator) if part.strip())

    @property
    def missing_label(self) -> str:
        return "Sin dato" if self.locale == "es" else "N/A"


def humanize_code(value: str) -> str:
    spaced = re.sub(r"[_\-]+", " ", value).strip()
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", spaced)
    spaced = re.sub(r"\s+", " ", spaced)
    return spaced[:1].upper() + spaced[1:] if spaced else "N/A"